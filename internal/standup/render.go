package standup

import (
	"fmt"
	"io"
	"time"
)

// Result carries everything Render needs for the final markdown.
type Result struct {
	Repo     string
	Window   time.Duration
	Model    string
	Date     time.Time
	Accepted []Bullet
	Rejected []Rejected
	Items    []Item
}

// Render writes the standup draft as markdown. Rejected lines are listed
// with their reasons instead of being dropped silently: the whole point of
// the tool is that you can see exactly what the model got wrong.
func Render(w io.Writer, r Result) {
	fmt.Fprintf(w, "# Standup draft - %s\n\n", r.Date.Format("2006-01-02"))
	fmt.Fprintf(w, "_Repo: `%s` - window: last %s - model: `%s`_\n\n", r.Repo, humanWindow(r.Window), r.Model)

	io.WriteString(w, "## What I worked on\n\n")
	if len(r.Accepted) == 0 {
		io.WriteString(w, "(no verified bullets - see rejected lines below)\n")
	}
	for _, b := range r.Accepted {
		fmt.Fprintf(w, "- %s\n", b.Text)
	}

	if uncovered := Uncovered(r.Accepted, r.Items); len(uncovered) > 0 {
		io.WriteString(w, "\n## Not covered by the draft\n\n")
		for _, it := range uncovered {
			if it.Kind == KindPR {
				fmt.Fprintf(w, "- #%s %s\n", it.ID, it.Title)
			} else {
				fmt.Fprintf(w, "- `%s` %s\n", it.ID, it.Title)
			}
		}
	}

	if len(r.Rejected) > 0 {
		io.WriteString(w, "\n## Rejected by the citation check\n\n")
		for _, rj := range r.Rejected {
			fmt.Fprintf(w, "- %s (%s)\n", rj.Line, rj.Reason)
		}
	}

	io.WriteString(w, "\n## Source commits the model read\n\n")
	for _, it := range r.Items {
		if it.Kind == KindPR {
			fmt.Fprintf(w, "- [#%s](%s) %s (merged %s)\n", it.ID, it.URL, it.Title, it.When.Format("Jan 2 15:04"))
		} else {
			fmt.Fprintf(w, "- `%s` %s - %s (%s)\n", it.ID, it.Title, it.Author, it.When.Format("Jan 2 15:04"))
		}
	}

	io.WriteString(w, "\n---\n")
	io.WriteString(w, "Draft generated by standup-sloth from git history. "+
		"It summarises what the commits say, which is not always the real work. "+
		"Edit it before you post it.\n")
}
